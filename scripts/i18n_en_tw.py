COSTUME_WORD_ALL_ZH_TW = {**COSTUME_COLORS_ZH_TW, **COSTUME_MODIFIERS_ZH_TW, **COSTUME_NOUNS_ZH_TW}

COSTUME_WORD_EN = {
    k: k.replace('-', ' ').title()
    for k in {**COSTUME_COLORS_ZH_TW, **COSTUME_MODIFIERS_ZH_TW, **COSTUME_NOUNS_ZH_TW}
}


def _merge_costume_tokens(kw: str) -> tuple[list[str], list[str]]:
    tokens = kw.split()
    merged = []
    i = 0
    while i < len(tokens):
        t = tokens[i]
        nxt = tokens[i + 1] if i + 1 < len(tokens) else None
        nxt2 = tokens[i + 2] if i + 2 < len(tokens) else None
        if t in ("olive", "mint") and nxt == "green":
            merged.append(t)
            i += 2
        elif t == "bra" and nxt == "briefs":
            merged.append("bra_briefs")
            i += 2
        elif t == "shirt" and nxt == "dress":
            merged.append("shirt_dress")
            i += 2
        elif t == "shirt" and nxt == "jacket":
            merged.append("shirt_jacket")
            i += 2
        elif t == "skirt" and nxt == "shorts":
            merged.append("skirt_shorts")
            i += 2
        elif t == "ribbon" and nxt in (
            "chiffon", "shirt", "blouse", "camisole", "dress", "knit", "cardigan", "sweater", "skirt"
        ):
            merged.append("ribbon_mod")
            i += 1
        elif t == "camisole" and nxt in ("dress", "mini", "midi", "maxi"):
            merged.append("camisole_mod")
            i += 1
        elif t == "corset" and nxt in ("dress", "mini", "midi", "maxi", "skirt"):
            merged.append("corset_mod")
            i += 1
        elif (
            t == "knit"
            and nxt not in ("dress", "cardigan", "sweater", "vest", "beanie", "skirt", "shorts", "pants", "camisole", "turtleneck")
            and not (nxt in ("mini", "midi", "maxi") and nxt2 == "dress")
        ):
            merged.append("knit_top")
            i += 1
        elif (
            t == "turtleneck"
            and nxt not in ("dress", "sweater", "knit")
            and not (nxt in ("mini", "midi", "maxi") and nxt2 == "dress")
        ):
            merged.append("turtleneck_top")
            i += 1
        else:
            merged.append(t)
            i += 1
    return tokens, merged


def translate_costume_keywords_zh_tw(kw: str) -> tuple[str, list[str]]:
    tokens, merged = _merge_costume_tokens(kw)
    ext_mods = dict(COSTUME_MODIFIERS_ZH_TW, ribbon_mod="蝴蝶結", camisole_mod="細肩帶", corset_mod="馬甲束腰")
    ext_nouns = dict(
        COSTUME_NOUNS_ZH_TW,
        bra_briefs="內衣套裝",
        shirt_dress="襯衫洋裝",
        shirt_jacket="襯衫夾克",
        skirt_shorts="褲裙",
        knit_top="針織衫",
        turtleneck_top="高領衫",
    )
    phrases = []
    buf = []
    for t in merged:
        if t in ext_nouns:
            phrases.append("".join(buf) + ext_nouns[t])
            buf = []
        elif t in COSTUME_COLORS_ZH_TW:
            if any(x in ext_mods.values() for x in buf):
                s = "".join(buf)
                if s.endswith(("蕾絲", "荷葉邊", "薄紗", "網紗", "緞面")):
                    s += "飾邊"
                phrases.append(s)
                buf = [COSTUME_COLORS_ZH_TW[t]]
            else:
                buf.append(COSTUME_COLORS_ZH_TW[t])
        elif t in ext_mods:
            buf.append(ext_mods[t])
        else:
            raise ValueError(f"Unknown costume token: {t}")
    if buf:
        s = "".join(buf)
        if s in ("金色", "銀色"):
            s += "飾品"
        elif s.endswith("迷你"):
            s += "包"
        elif s.endswith(("蕾絲", "荷葉邊", "薄紗", "網紗", "緞面")):
            s += "配飾"
        elif s in COSTUME_COLORS_ZH_TW.values():
            s += "配飾"
        phrases.append(s)

    word_tags = []
    for w in tokens:
        zh = COSTUME_WORD_ALL_ZH_TW[w]
        if zh not in word_tags:
            word_tags.append(zh)
    return "・".join(phrases), word_tags


def translate_costume_keywords_en(kw: str) -> tuple[str, list[str]]:
    tokens, merged = _merge_costume_tokens(kw)
    ext_mods = {
        **{k: k.replace("-", " ").title() for k in COSTUME_MODIFIERS_ZH_TW},
        "ribbon_mod": "Ribbon",
        "camisole_mod": "Camisole",
        "corset_mod": "Corset",
    }
    ext_nouns = {
        **{k: k.replace("-", " ").title() for k in COSTUME_NOUNS_ZH_TW},
        "bra_briefs": "Lingerie Set",
        "shirt_dress": "Shirt Dress",
        "shirt_jacket": "Shirt Jacket",
        "skirt_shorts": "Skort",
        "knit_top": "Knit Top",
        "turtleneck_top": "Turtleneck Top",
    }
    colors_en = {
        **{k: k.replace("-", " ").title() for k in COSTUME_COLORS_ZH_TW},
        "olive": "Olive Green",
        "mint": "Mint Green",
    }
    phrases = []
    buf = []
    for t in merged:
        if t in ext_nouns:
            phrases.append(" ".join([*buf, ext_nouns[t]]))
            buf = []
        elif t in colors_en:
            if any(x in ext_mods.values() for x in buf):
                s = " ".join(buf)
                if buf[-1] in ("Lace", "Frill", "Tulle", "Mesh", "Satin"):
                    s += " Trim"
                phrases.append(s)
                buf = [colors_en[t]]
            else:
                buf.append(colors_en[t])
        elif t in ext_mods:
            buf.append(ext_mods[t])
        else:
            raise ValueError(f"Unknown costume token: {t}")
    if buf:
        last = buf[-1]
        s = " ".join(buf)
        if s in ("Gold", "Silver"):
            s += " Jewelry"
        elif last == "Mini":
            s += " Bag"
        elif last in ("Lace", "Frill", "Tulle", "Mesh", "Satin"):
            s += " Accent"
        elif s in colors_en.values():
            s += " Trim"
        phrases.append(s)

    word_tags = []
    for w in tokens:
        en_w = COSTUME_WORD_EN[w]
        if en_w not in word_tags:
            word_tags.append(en_w)
    return " · ".join(phrases), word_tags
